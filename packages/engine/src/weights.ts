/**
 * 位置权重表（L1-L3 静态启发）。
 * 角 200 / X 位 −100 / C 位 −25 / 边 +15。
 * 索引 = y * 8 + x。
 */
export const POSITION_WEIGHTS: readonly number[] = [
  //  y=0
  200, -100, 15, 15, 15, 15, -100, 200,
  //  y=1
  -100, -100, -25, -25, -25, -25, -100, -100,
  //  y=2
  15, -25, 5, 5, 5, 5, -25, 15,
  //  y=3
  15, -25, 5, 5, 5, 5, -25, 15,
  //  y=4
  15, -25, 5, 5, 5, 5, -25, 15,
  //  y=5
  15, -25, 5, 5, 5, 5, -25, 15,
  //  y=6
  -100, -100, -25, -25, -25, -25, -100, -100,
  //  y=7
  200, -100, 15, 15, 15, 15, -100, 200,
] as const

/** 获取某位置的权重 */
export function weightAt(x: number, y: number): number {
  return POSITION_WEIGHTS[y * 8 + x] ?? 0
}
